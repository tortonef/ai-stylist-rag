"""Evaluation: parser accuracy, constraint satisfaction, grounding and latency. Writes docs/eval_results.md.

python -m ai_stylist.evaluate          # retrieval only (seconds)
python -m ai_stylist.evaluate --llm    # also full mode with Ollama (minutes on CPU)
"""

from __future__ import annotations

import argparse
import statistics
import sys
import time
from datetime import date

import yaml

from . import llm
from .catalog import load_catalog
from .config import load_config
from .embed import load_encoder
from .index import load_or_build
from .query import Query, load_vocabulary
from .stylist import SKU, answer

FIELDS = ["occasions", "gender", "categories", "season", "budget"]


def violations(p: dict, expect: dict, per_item_budget: bool) -> list[str]:
    """Expected constraints this product breaks."""
    out = []
    if expect.get("gender") and p["gender"] not in (expect["gender"], "unisex"):
        out.append("gender")
    if expect.get("categories") and p["category"] not in expect["categories"]:
        out.append("category")
    if expect.get("season") and p["season"] not in (expect["season"], "all-season"):
        out.append("season")
    if expect.get("occasions") and not set(expect["occasions"]) & set(p["occasions"]):
        out.append("occasion")
    if per_item_budget and expect.get("budget") is not None and p["price_eur"] > expect["budget"]:
        out.append("budget")
    return out


def parsed_ok(q: Query, expect: dict) -> dict[str, bool]:
    return {
        f: (getattr(q, f) or None) == (expect.get(f) or None)
        if f != "categories"
        else sorted(q.categories) == sorted(expect.get("categories", []))
        for f in FIELDS
    }


def run(with_llm: bool) -> list[dict]:
    cfg = load_config()
    p = cfg["paths"]
    products = load_catalog(p["catalog"], p["schema"])
    encoder = load_encoder(cfg)
    vectors = load_or_build(cfg, products, encoder)
    vocab = load_vocabulary(p["vocabulary"])
    with p["eval_queries"].open(encoding="utf-8") as f:
        queries = yaml.safe_load(f)
    if with_llm and (reason := llm.unavailable_reason(cfg)):
        sys.exit(f"--llm needs Ollama: {reason}")

    raw_answers: dict[str, str] = {}

    def recording_chat(messages: list[dict], c: dict) -> str:
        text = llm.chat(messages, c)
        raw_answers["last"] = text
        return text

    rows = []
    for item in queries:
        e = item["expect"]
        a = answer(item["text"], cfg, products, vectors, encoder, vocab, False)
        row = {"id": item["id"], "text": item["text"], "expect": e, "answer": a}
        look_expected = e.get("look")
        row["look_ok"] = None if look_expected is None else (a.look is not None) == look_expected
        if a.look and e.get("budget") is not None:
            row["look_ok"] = row["look_ok"] and a.look.total <= e["budget"]
        per_item = a.look is None
        row["bad_items"] = {
            h.product["sku"]: v for h in a.hits if (v := violations(h.product, e, per_item))
        }
        row["parsed"] = parsed_ok(a.query, e)
        if with_llm:
            raw_answers.clear()
            t0 = time.perf_counter()
            full = answer(
                item["text"], cfg, products, vectors, encoder, vocab, True, chat=recording_chat
            )
            row["gen_s"] = time.perf_counter() - t0
            allowed = {h.product["sku"] for h in full.hits}
            raw = raw_answers.get("last", "")
            row["raw_unknown"] = sorted({s for s in SKU.findall(raw) if s not in allowed})
            row["final_unknown"] = sorted({s for s in SKU.findall(full.text) if s not in allowed})
            row["full"] = full
        rows.append(row)
    return rows


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "n/a"


def report(rows: list[dict], with_llm: bool, model: str) -> str:
    items = sum(len(r["answer"].hits) for r in rows)
    bad = sum(len(r["bad_items"]) for r in rows)
    looks = [r for r in rows if r["look_ok"] is not None]
    fields_ok = {f: sum(r["parsed"][f] for r in rows) for f in FIELDS}
    ret_ms = statistics.mean(r["answer"].retrieval_s for r in rows) * 1000
    lines = [
        "# Evaluation results",
        "",
        f"Generated by `python -m ai_stylist.evaluate{' --llm' if with_llm else ''}` on {date.today()} "
        f"with {len(rows)} queries from [`data/eval/queries.yaml`](../data/eval/queries.yaml) "
        "against the 79-product sample catalog. Expected constraints are what a human stylist would "
        "read in each question, so parser misses count as failures.",
        "",
        "## Summary",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Retrieved items satisfying every expected constraint | {pct(items - bad, items)} |",
        f"| Outfit questions handled correctly (look within total budget, or none when impossible) | {pct(sum(r['look_ok'] for r in looks), len(looks))} |",
        f"| Queries where every parsed filter matches the expectation | {pct(sum(all(r['parsed'].values()) for r in rows), len(rows))} |",
        f"| Average retrieval latency (retrieval-only mode) | {ret_ms:.0f} ms |",
    ]
    if with_llm:
        raw_bad = sum(len(r["raw_unknown"]) for r in rows)
        final_bad = sum(len(r["final_unknown"]) for r in rows)
        gen = [r["gen_s"] for r in rows]
        lines += [
            f"| SKUs cited by the model that were not retrieved, before the grounding check | {raw_bad} in {pct(sum(bool(r['raw_unknown']) for r in rows), len(rows))} answers |",
            f"| Hallucinated SKUs shown to the shopper, after the grounding check | {final_bad} |",
            f"| Answers that fell back to the template (LLM error) | {sum(r['full'].mode != 'full' for r in rows)} |",
            f"| Average full-mode latency ({model}) | {statistics.mean(gen):.1f} s (max {max(gen):.1f} s) |",
            "",
            "Full-mode latency depends on the hardware: Ollama uses a GPU when it finds one. "
            "See the README for CPU-only timings.",
        ]
    else:
        lines.append("| Grounding and full-mode latency | not run (needs `--llm` and Ollama) |")
    lines += [
        "",
        "## Parser accuracy per field",
        "",
        "| Field | Correct |",
        "|---|---|",
        *[f"| {f} | {pct(fields_ok[f], len(rows))} |" for f in FIELDS],
        "",
        "## Per query",
        "",
        "| ID | Question | Shown | Look | Violations | Parser misses |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        a = r["answer"]
        look = "-" if r["look_ok"] is None else ("ok" if r["look_ok"] else "FAIL")
        if a.look:
            look += f" (€{a.look.total:g})"
        viol = "; ".join(f"{s}: {', '.join(v)}" for s, v in r["bad_items"].items()) or "none"
        misses = ", ".join(f for f, ok in r["parsed"].items() if not ok) or "none"
        lines.append(f"| {r['id']} | {r['text']} | {len(a.hits)} | {look} | {viol} | {misses} |")
    if with_llm:
        lines += ["", "## Sample generated answers", ""]
        for r in rows[:3]:
            lines += [f"**{r['text']}**", "", f"> {r['full'].text}", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--llm", action="store_true", help="also evaluate full mode with Ollama")
    args = ap.parse_args()
    cfg = load_config()
    rows = run(args.llm)
    md = report(rows, args.llm, cfg["ollama"]["model"])
    out = cfg["paths"]["eval_report"]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(md, encoding="utf-8", newline="\n")
    print(md)


if __name__ == "__main__":
    main()
